import java.io.ByteArrayOutputStream

plugins {
    alias(libs.plugins.android.application)
}

// Release signing comes from the environment (set by CI from repository
// secrets). Watch Face Push wants faces signed with their own key, different
// from the app's (SIGNING_*). Unsigned release faces fail validation.
val signingKeystore: String? = System.getenv("FACE_SIGNING_KEYSTORE")

android {
    namespace = "dev.stackon.sloppyshock.watchface"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        // Watch Face Push requires <app package>.watchfacepush.<face>; the
        // flavor suffix adds the face name.
        applicationId = "dev.stackon.sloppyshock.watchfacepush"
        minSdk = 35
        targetSdk = 37
        // CI passes -PversionCode / -PversionName derived from the run and tag.
        versionCode = (findProperty("versionCode") as String?)?.toInt() ?: 18
        versionName = (findProperty("versionName") as String?) ?: "1.0"

    }

    // One watch face per layout (sources generated by tools/gen_watchface.py
    // into src/<flavor>/res).
    flavorDimensions += "layout"
    productFlavors {
        create("compact") {
            dimension = "layout"
            applicationIdSuffix = ".compact"
        }
        create("detailed") {
            dimension = "layout"
            applicationIdSuffix = ".detailed"
        }
        create("dual") {
            dimension = "layout"
            applicationIdSuffix = ".dual"
        }
    }

    signingConfigs {
        if (signingKeystore != null) {
            create("release") {
                storeFile = file(signingKeystore)
                storePassword = System.getenv("FACE_SIGNING_STORE_PASSWORD")
                keyAlias = System.getenv("FACE_SIGNING_KEY_ALIAS")
                keyPassword = System.getenv("FACE_SIGNING_KEY_PASSWORD")
            }
        }
    }

    // Pushed watch faces may contain only the manifest and resources: R8 drops
    // the (unused) R classes so no classes.dex is packaged. Resource shrinking
    // must stay off - watchface.xml references fonts/drawables by name only.
    buildTypes {
        debug {
            isMinifyEnabled = true
            isShrinkResources = false
        }
        release {
            if (signingKeystore != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            isMinifyEnabled = true
            isShrinkResources = false
        }
    }
    enableKotlin = false
}

val validator: Configuration = configurations.create("validator")

dependencies {
    validator(libs.watchface.validator.cli)
}

// Package name of the marketplace app that pushes these faces.
val pushClientPackage = "dev.stackon.sloppyshock"

/**
 * Validates one face APK with Google's Watch Face Push validator and writes
 * `<face>.apk` + `<face>_token.txt` (the token Watch Face Push requires) to
 * [outputDir]. Fails the build if validation fails.
 */
abstract class ValidateWatchFaceTask : DefaultTask() {
    @get:Inject abstract val execOps: ExecOperations
    @get:InputFiles @get:PathSensitive(PathSensitivity.NONE) abstract val apkDir: DirectoryProperty
    @get:Classpath abstract val validatorClasspath: ConfigurableFileCollection
    @get:Input abstract val clientPackage: Property<String>
    @get:Input abstract val faceName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun validate() {
        val apk = apkDir.get().asFile.listFiles { f -> f.extension == "apk" }!!.single()
        val log = ByteArrayOutputStream()
        execOps.javaexec {
            classpath = validatorClasspath
            mainClass.set("com.google.android.wearable.watchface.validator.cli.DwfValidation")
            args("--apk_path=${apk.absolutePath}", "--package_name=${clientPackage.get()}")
            standardOutput = log
            errorOutput = log
            isIgnoreExitValue = true
        }
        val text = log.toString()
        val token = Regex("""generated token: (\S+)""").find(text)?.groupValues?.get(1)
            ?: throw GradleException("Watch Face Push validation failed for ${apk.name}:\n$text")
        val out = outputDir.get().asFile.apply { deleteRecursively(); mkdirs() }
        apk.copyTo(out.resolve("${faceName.get()}.apk"))
        out.resolve("${faceName.get()}_token.txt").writeText(token)
    }
}

// validate<Flavor><BuildType>: build/watchfacepush/<variant>/<flavor>.apk + token.
androidComponents.onVariants { variant ->
    tasks.register<ValidateWatchFaceTask>("validate${cap(variant.name)}") {
        apkDir.set(variant.artifacts.get(com.android.build.api.artifact.SingleArtifact.APK))
        validatorClasspath.from(validator)
        clientPackage.set(pushClientPackage)
        faceName.set(variant.flavorName!!)
        outputDir.set(layout.buildDirectory.dir("watchfacepush/${variant.name}"))
    }
}


// One APK per watch face (WFF allows a single face per APK). These tasks treat
// the three faces as one deliverable.
val faceFlavors = listOf("compact", "detailed", "dual")
fun cap(s: String) = s.replaceFirstChar(Char::uppercase)

// Installs all faces directly (adb), bypassing Watch Face Push - for devices
// without it, e.g. a Wear OS 5 emulator. Pick the device with ANDROID_SERIAL.
tasks.register("installAllFaces") {
    group = "install"
    description = "Installs the debug APKs of all watch face layouts."
    dependsOn(faceFlavors.map { "install${cap(it)}Debug" })
}
