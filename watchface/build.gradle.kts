plugins {
    alias(libs.plugins.android.application)
}

// Release signing comes from the environment (set by CI from repository
// secrets); without it release APKs are left unsigned.
val signingKeystore: String? = System.getenv("SIGNING_KEYSTORE")

android {
    namespace = "com.example.sloppyshock"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.example.sloppyshock"
        minSdk = 35
        targetSdk = 37
        // CI passes -PversionCode / -PversionName derived from the run and tag.
        versionCode = (findProperty("versionCode") as String?)?.toInt() ?: 3
        versionName = (findProperty("versionName") as String?) ?: "1.0"

    }

    // One watch face per layout (sources generated by tools/gen_watchface.py
    // into src/<flavor>/res). "compact" keeps the original package name.
    flavorDimensions += "layout"
    productFlavors {
        create("compact") {
            dimension = "layout"
        }
        create("detailed") {
            dimension = "layout"
            applicationIdSuffix = ".detailed"
        }
        create("dual") {
            dimension = "layout"
            applicationIdSuffix = ".dual"
        }
    }

    signingConfigs {
        if (signingKeystore != null) {
            create("release") {
                storeFile = file(signingKeystore)
                storePassword = System.getenv("SIGNING_STORE_PASSWORD")
                keyAlias = System.getenv("SIGNING_KEY_ALIAS")
                keyPassword = System.getenv("SIGNING_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            if (signingKeystore != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            // No code to optimize, and resource shrinking would strip the face:
            // watchface.xml references fonts/drawables by name only.
            optimization {
                enable = false
            }
        }
    }
    enableKotlin = false
}

dependencies {
}

// One APK per watch face (WFF allows a single face per APK). These tasks treat
// the three faces as one deliverable.
val faceFlavors = listOf("compact", "detailed", "dual")
fun cap(s: String) = s.replaceFirstChar(Char::uppercase)

// Installs all faces on the connected device(s). With several devices attached
// (e.g. a phone), pick the watch with ANDROID_SERIAL=<serial>.
tasks.register("installAllFaces") {
    group = "install"
    description = "Installs the debug APKs of all watch face layouts."
    dependsOn(faceFlavors.map { "install${cap(it)}Debug" })
}

// Zips the three debug APKs into build/dist/ as a single file to share.
tasks.register<Zip>("zipFaces") {
    group = "distribution"
    description = "Packages the debug APKs of all watch face layouts into one zip."
    dependsOn(faceFlavors.map { "assemble${cap(it)}Debug" })
    from(faceFlavors.map { layout.buildDirectory.file("outputs/apk/$it/debug/watchface-$it-debug.apk") })
    archiveFileName.set("sloppyshock-watchfaces.zip")
    destinationDirectory.set(layout.buildDirectory.dir("dist"))
}